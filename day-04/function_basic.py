"""1. Function কী?
Function হলো Python-এর এমন একটি Code Block, যেটি নির্দিষ্ট কাজ সম্পন্ন করে এবং প্রয়োজন হলে বারবার ব্যবহার করা যায়।

ধরো, তুমি একটি প্রোগ্রামে ১০ বার Hello print করতে চাও। প্রতিবার একই কোড না লিখে একটি Function তৈরি করতে পারো।"""


#without Function
print("Hello Abedin")
print("Hello Abedin")
print("Hello Abedin")

#Use Funtion
def say_hello():
    print("Hello Abedin")

say_hello()
say_hello()
say_hello()


"""def	Function তৈরি করে
function_name	Function-এর নাম
()	Parentheses
function_name()	Function Call করে"""




